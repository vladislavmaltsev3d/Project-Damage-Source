def create(library, factory):
    result = {}
    for index, (family, key, description, bases, overrides) in enumerate(RECIPES):
        effects, values, settings = [], {}, {}
        for base in bases:
            recipe = library[base]
            for effect in recipe['effects']:
                if effect not in effects: effects.append(effect)
            values.update(deepcopy(recipe['props']))
            for group, fields in recipe['settings'].items():
                settings.setdefault(group, {}).update(deepcopy(fields))
        values.update(overrides)
        values['seed'] = 401 + index * 17
        values['damage_shading'] = True
        values['base_smooth_angle'] = 0.0
        values['preserve_data'] = True
        values['brick_remesh'] = False
        if family == 'metal':
            for name in ('rusty_size_min', 'rusty_size_max'):
                if name in values: values[name] *= 2.2
            for name in ('bullet_size_min', 'bullet_size_max'):
                if name in values: values[name] *= 2.5
        if 'weld' in settings:
            settings['weld']['edge_type'] = '1'
            settings['weld']['angle'] = 75.0
            if 'edge' in effects:
                values['amount'] = min(values.get('amount', 16), 16)
        assert len(effects) >= 2, key
        result[key] = factory('combined_' + family, description, effects, values, settings)
    return result
